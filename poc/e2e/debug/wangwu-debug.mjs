import { chromium } from 'playwright'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1400, height: 900 } })
const page = await ctx.newPage()
page.on('console', m => { if (m.type() === 'error') console.log('ERR', m.text()) })
await page.goto(process.argv[2], { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2500)
console.log('url', page.url())
console.log('body1', (await page.locator('body').innerText()).replace(/\s+/g,' ').slice(0,600))
const entry = page.getByRole('button', { name: /研发工作台/ }).first()
if (await entry.isVisible().catch(()=>false)) { await entry.click(); await page.waitForTimeout(1500) }
console.log('body2', (await page.locator('body').innerText()).replace(/\s+/g,' ').slice(0,1200))
console.log('buttons', (await page.getByRole('button').allInnerTexts()).slice(0,40).join(' | '))
await page.screenshot({ path: '/Users/kirer/projects/da-Workbench/poc/deploy/dsh-sim/screenshots/wangwu-debug.png' })
await browser.close()
