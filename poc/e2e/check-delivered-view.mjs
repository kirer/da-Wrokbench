import { chromium } from 'playwright'
const url = process.argv[2]
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 }, colorScheme: 'dark' })
const page = await ctx.newPage()
page.on('console', msg => { if (msg.type() === 'error') console.log('CONSOLE-ERROR', msg.text()) })
page.on('pageerror', err => console.log('PAGE-ERROR', err.message))
await page.goto(url, { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2200)
const entry = page.getByRole('button', { name: /研发工作台/ }).first()
if (await entry.isVisible().catch(() => false)) { await entry.click(); await page.waitForTimeout(800) }
const login = page.getByRole('button', { name: /李四[\s\S]*进入/ }).first()
if (await login.isVisible().catch(() => false)) { await login.click(); await page.waitForTimeout(2200) }
await page.getByRole('row', { name: /2026-S11/ }).first().click()
await page.waitForTimeout(700)
await page.getByRole('button', { name: '会员积分改版', exact: true }).first().click()
await page.waitForTimeout(700)
await page.getByRole('button', { name: '进入会话', exact: true }).first().click()
await page.waitForTimeout(3500)
await page.getByRole('button', { name: /^设计交付 \d+$/ }).first().click()
await page.waitForTimeout(3500)
const modeButton = page.locator('.dsh-wb-canvas-mode button').last()
console.log('mode button', await modeButton.innerText(), await modeButton.isVisible())
await modeButton.click()
await page.waitForTimeout(1200)
console.log('gallery', (await page.locator('.dsh-wb-gallery-body').innerText().catch(() => '')).replace(/\s+/g, ' ').slice(0, 500))
console.log('caption', (await page.locator('.dsh-wb-gallery-caption').innerText().catch(() => '')).replace(/\s+/g, ' '))
await page.screenshot({ path: '/Users/kirer/projects/da-Workbench/poc/deploy/dsh-sim/screenshots/lisi-delivered-view.png' })
await browser.close()
